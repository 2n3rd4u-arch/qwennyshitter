#!/usr/bin/env bash
# One-time setup of the Android SDK + NDK used by scripts/build-android.sh.
#
# Installs (into $ANDROID_HOME, default /opt/android-sdk):
#   - command-line tools
#   - platform-tools (adb)
#   - platforms;android-35 and build-tools;35.0.0  (match app/build.gradle)
#   - ndk;27.2.12479018
#   - cmake;3.31.6
# Accepts all licenses, then writes android/local.properties so Gradle picks
# up the exact same SDK/NDK.
#
# Idempotent: safe to re-run; already-installed packages are skipped.

set -euo pipefail
source "$(dirname "$0")/env.sh"

ANDROID_HOME="${ANDROID_HOME:-/opt/android-sdk}"
SDKMANAGER="$ANDROID_HOME/cmdline-tools/latest/bin/sdkmanager"

if [[ ! -x "$SDKMANAGER" ]]; then
    echo ">> Downloading Android command-line tools ($CMDLINE_TOOLS_VERSION)..."
    mkdir -p "$ANDROID_HOME/cmdline-tools"
    tmp="$(mktemp -d)"
    curl -fsSL -o "$tmp/tools.zip" \
        "https://dl.google.com/android/repository/commandlinetools-linux-${CMDLINE_TOOLS_VERSION}_latest.zip"
    if command -v unzip >/dev/null 2>&1; then
        unzip -q "$tmp/tools.zip" -d "$ANDROID_HOME/cmdline-tools"
    else
        python3 -c "import sys,zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])" \
            "$tmp/tools.zip" "$ANDROID_HOME/cmdline-tools"
    fi
    rm -rf "$ANDROID_HOME/cmdline-tools/latest"
    mv "$ANDROID_HOME/cmdline-tools/cmdline-tools" "$ANDROID_HOME/cmdline-tools/latest"
    chmod +x "$ANDROID_HOME/cmdline-tools/latest/bin/"*
    rm -rf "$tmp"
fi

echo ">> Accepting SDK licenses..."
yes | "$SDKMANAGER" --licenses >/dev/null || true

echo ">> Installing SDK packages..."
"$SDKMANAGER" \
    "platform-tools" \
    "platforms;$SDK_PLATFORM_VERSION" \
    "build-tools;$SDK_BUILD_TOOLS_VERSION" \
    "ndk;$NDK_VERSION" \
    "cmake;3.31.6"

# Write local.properties so Gradle uses this exact SDK/NDK.
NDK_PATH="$ANDROID_HOME/ndk/$NDK_VERSION"
echo ">> Writing android/local.properties..."
cat > "$REPO_ROOT/android/local.properties" <<EOF
# Generated by scripts/setup-android-sdk.sh — do not commit.
sdk.dir=$ANDROID_HOME
ndk.dir=$NDK_PATH
EOF

echo ">> Verifying..."
"$NDK_PATH/ndk-build" --version | head -2 || true
aapt2_path="$ANDROID_HOME/build-tools/$SDK_BUILD_TOOLS_VERSION/aapt2"
[[ -x "$aapt2_path" ]] && echo "build-tools OK: $aapt2_path"

echo
echo "Android SDK ready at: $ANDROID_HOME"
echo "NDK ready at:         $NDK_PATH"
echo "Now run:              scripts/build-android.sh"
